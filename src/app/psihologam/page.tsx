import Link from "next/link";
import type { Metadata } from "next";
import { getAllTests, getAllConstructs } from "@/lib/content";
import { SITE, platformLink } from "@/lib/site";
import Breadcrumbs from "@/components/Breadcrumbs";
import ExpertCta from "@/components/ExpertCta";

export const metadata: Metadata = {
  title: "Психологам: методики с ключами, нормами и правовым основанием",
  description:
    "Открытые методики с указанием источника, надёжности и правового основания использования. Что можно применять в практике бесплатно и на каких условиях.",
  alternates: { canonical: `${SITE.url}/psihologam` },
};

/**
 * Вторая воронка сайта: не клиент с результатом, а специалист, который ищет
 * ключи и нормы методики. Профессиональный хвост запросов («методика X ключи»)
 * в русской выдаче почти пуст, а страница-паспорт отвечает на него точно.
 */
export default function ForPsychologistsPage() {
  const tests = getAllTests();
  const publicDomain = tests.filter((t) => t.passport.rightsBasis === "public_domain");
  const ownWork = tests.filter((t) => t.passport.rightsBasis === "own_work");
  const constructs = getAllConstructs();
  const withAlpha = tests.filter((t) => /α ≈ [0-9.]+/.test(t.passport.reliability));

  const faq = [
    {
      q: "Можно ли использовать эти методики в своей практике?",
      a: `Те, что помечены как общественное достояние, — да, включая коммерческое использование: это ${publicDomain.length} методик из пула IPIP, права на который открыты с 1999 года явным разрешением авторов. Ещё ${ownWork.length} методик написаны нами с нуля. На каждой странице паспорта указано основание и ссылка на источник — при необходимости её можно проверить.`,
    },
    {
      q: "Есть ли нормы для русскоязычной выборки?",
      a: "Нет, и мы это пишем на каждой странице. Русские переводы независимой психометрической проверки не проходили, поэтому результат показывается как процент от максимума шкалы, а не как процентиль. Коэффициент надёжности приводится для англоязычного оригинала со ссылкой на источник — переносить его на перевод строго говоря нельзя, и в паспорте это оговорено.",
    },
    {
      q: "Где взять ключи и направление пунктов?",
      a: "Страница паспорта показывает состав шкалы: сколько пунктов, сколько из них обратных, что именно измеряется и чего методика не показывает. Сам расчёт — сумма по шкале с разворотом обратных пунктов, без взвешивания и без скрытых коэффициентов.",
    },
    {
      q: "Зачем вам это, если сайт бесплатный?",
      a: `Сайт не продаёт тесты и не показывает рекламу. Он приводит людей на ${SITE.platform.name} — платформу, где психологи ведут консультации. Клиент приходит с готовым результатом, специалист получает клиента. Это и есть модель.`,
    },
  ];

  const faqLd = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faq.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: { "@type": "Answer", text: item.a },
    })),
  };

  return (
    <>
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(faqLd) }} />
      <Breadcrumbs items={[{ name: "Главная", href: "/" }, { name: "Психологам", href: "/psihologam" }]} />

      <h1>Психологам: методики с источниками и правовым основанием</h1>
      <p className="lead">
        {tests.length} методик, у каждой открытый паспорт: что измеряет, из какой шкалы взята, какая надёжность у
        оригинала, чего не показывает и на каком основании её можно использовать. Без «уникальных авторских методик» и
        без ключей за деньги.
      </p>

      <section>
        <h2>Что здесь есть</h2>
        <ul>
          <li>
            <strong>{publicDomain.length} методик из пула IPIP</strong> — общественное достояние с 1999 года,
            коммерческое использование разрешено авторами явно. Перевод наш.
          </li>
          <li>
            <strong>{ownWork.length} собственных методик</strong> — пункты написаны с нуля, защищённые опросники не
            воспроизводились.
          </li>
          <li>
            <strong>{withAlpha.length} методик с указанной надёжностью оригинала</strong> — коэффициент α приводится с
            оговоркой, что он относится к англоязычной версии, а не к переводу.
          </li>
        </ul>
        <p>
          <Link href="/methods" className="btn secondary">
            Открыть паспорта методик
          </Link>
        </p>
      </section>

      <section>
        <h2>Чего здесь нет</h2>
        <p>
          Нет СМИЛ, Кеттелла, Люшера, Айзенка, Роршаха и других защищённых или лицензируемых инструментов — ни в
          оригинале, ни «по мотивам». Это не осторожность, а условие: сайт используется коммерчески, и переопубликация
          чужих адаптаций означала бы нарушение. Нет и норм российской выборки — их сбор требует отдельного
          исследования, и пока его нет, мы не показываем процентили.
        </p>
        <p>
          Клинических шкал в открытом доступе тоже нет. Скрининговые инструменты работают в руках специалиста, который
          назначает их и интерпретирует, а не в формате «пройди и узнай диагноз».
        </p>
      </section>

      <section>
        <h2>Как это устроено технически</h2>
        <p>
          Прохождение анонимно и без регистрации. Ответы нигде не сохраняются: результат кодируется в ссылку, поэтому
          клиент может прислать её вам, и вы увидите ровно то же, что видел он. История прохождений, если человек её
          включил, лежит в его браузере и никуда не отправляется.
        </p>
        <p>
          Практический смысл для приёма: клиент приходит с уже готовым результатом и словами, которыми он про себя
          думает. Это экономит первую встречу — вместо сбора анамнеза с нуля можно начать с того, что человека
          зацепило в описании.
        </p>
      </section>

      {constructs.length > 0 && (
        <section>
          <h2>Разборы тем</h2>
          <p className="muted small">
            Эти страницы можно давать клиентам между встречами — они написаны без обещаний и без диагнозов.
          </p>
          <ul className="clean">
            {constructs.map((c) => (
              <li key={c.slug}>
                <Link href={`/constructs/${c.slug}`}>{c.title}</Link>
              </li>
            ))}
          </ul>
        </section>
      )}

      <h2>Частые вопросы</h2>
      {faq.map((item) => (
        <section key={item.q}>
          <h3>{item.q}</h3>
          <p>{item.a}</p>
        </section>
      ))}

      <div className="cta">
        <h2>Вести консультации на {SITE.platform.name}</h2>
        <p>
          Люди приходят сюда с конкретным вопросом о себе и с результатом на руках — часть из них ищет специалиста в
          тот же день. На {SITE.platform.name} у вас профиль со специализацией, онлайн-запись и оплата; комиссия с
          сессий не берётся, откликов за деньги нет.
        </p>
        <p>
          <ExpertCta href={platformLink({ campaign: "for_psychologists", content: "expert" })} placement="psihologam">
            Как начать практику на {SITE.platform.name}
          </ExpertCta>
        </p>
      </div>
    </>
  );
}
