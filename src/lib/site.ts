/**
 * Ссылки на платформу размечены UTM: каждая ячейка тегируется своими метками,
 * атрибуция — через уникальные ссылки (правило аналитики MainExperts).
 * Решения принимаются по сквозной атрибуции до оплаты, не по CPL.
 */
export function platformLink(params: {
  campaign: string;
  content?: string;
  path?: string;
}): string {
  const url = new URL(params.path || "/", SITE.platform.url);
  url.searchParams.set("utm_source", "psytests");
  url.searchParams.set("utm_medium", "organic_test");
  url.searchParams.set("utm_campaign", params.campaign);
  if (params.content) url.searchParams.set("utm_content", params.content);
  return url.toString();
}

