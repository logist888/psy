import { describe, expect, it } from "vitest";
import { getAllTests } from "../src/lib/content";

/**
 * Формулировки пунктов: их читает каждый, кто проходит тест, и незаметная
 * небрежность стоит доверия к странице.
 */

const tests = getAllTests();

/**
 * Русский язык выдаёт род в прошедшем времени и кратких прилагательных, и
 * утверждение о себе перестаёт подходить половине аудитории: «Большую часть
 * времени я спокоен» женщина читает как чужую фразу. Пункты пишутся так,
 * чтобы род не всплывал: настоящее время, безличные и глагольные обороты.
 */
const GENDERED =
  /\b(был|была|стал|стала|сделал|сделала|готов|уверен|рад|должен|способный|доволен|занят|спокоен|устал|склонен|намерен|вынужден)\b(?![аоиыя])/i;

/**
 * Третье лицо — не про отвечающего, род там принадлежит другому человеку и
 * ничего не ломает: «успокоить человека, который расстроен».
 */
const THIRD_PERSON = /\b(человек[а-я]*|партнёр[а-я]*|каждый|собеседник[а-я]*|друг|коллег[а-я]+)\b/i;

describe("формулировки пунктов", () => {
  it("утверждения о себе не выдают род отвечающего", () => {
    const offenders: string[] = [];
    for (const t of tests) {
      for (const q of t.questions) {
        if (GENDERED.test(q.text) && !THIRD_PERSON.test(q.text)) {
          offenders.push(`${t.slug}.${q.id}: ${q.text}`);
        }
      }
    }
    expect(offenders, `родовые формы в утверждениях:\n${offenders.join("\n")}`).toEqual([]);
  });

  it("в утверждениях нет диагностической лексики", () => {
    // Сайт не ставит диагнозов: такие слова в пункте превращают самоотчёт в
    // подобие клинического опроса и нарушают рамку, на которой стоит проект.
    const clinical = /\b(диагноз|патолог|расстройств|симптом|синдром|невроз|психоз|депрессия|шизофрен)/i;
    const offenders: string[] = [];
    for (const t of tests) {
      for (const q of t.questions) if (clinical.test(q.text)) offenders.push(`${t.slug}.${q.id}: ${q.text}`);
    }
    expect(offenders, `клиническая лексика в утверждениях:\n${offenders.join("\n")}`).toEqual([]);
  });
});
